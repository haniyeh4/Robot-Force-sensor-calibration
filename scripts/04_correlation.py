"""Correlation analysis (Section 4.3, Figures 11-12), on the dynamic training pool (L1 + L2).

Note: the original Figures 11-12 were generated by code that is no longer available;
this script recomputes them on the same recordings used to train the dynamic models.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from forcecal.data import DYN_TRAIN_POOL, FIGURES_DIR, RESULTS_DIR, load_dyn, stack
from forcecal.metrics import save


def heatmap(c, labels, title, fname, annotate=True):
    fig, ax = plt.subplots(figsize=(0.55 * len(labels) + 2.5, 0.55 * len(labels) + 1.8))
    im = ax.imshow(c, vmin=-1, vmax=1, cmap="coolwarm")
    ax.set_xticks(range(len(labels)), labels, rotation=60, ha="right")
    ax.set_yticks(range(len(labels)), labels)
    if annotate:
        for i in range(len(labels)):
            for j in range(len(labels)):
                ax.text(j, i, f"{c[i, j]:.2f}", ha="center", va="center", fontsize=7)
    fig.colorbar(im, ax=ax, fraction=0.046)
    ax.set_title(title)
    FIGURES_DIR.mkdir(exist_ok=True)
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / fname, dpi=200)
    plt.close(fig)
    print(f"wrote figures/{fname}")


def main():
    pool = [load_dyn(i) for i in DYN_TRAIN_POOL]
    pos, xdd, y = stack(pool, "pos"), stack(pool, "xdd"), stack(pool, "y")

    # Figure 11: linear acceleration vs dynamic force offset
    lab11 = ["ax", "ay", "az", "Fx_dyn", "Fy_dyn", "Fz_dyn"]
    c11 = np.corrcoef(np.hstack([xdd[:, :3], y[:, :3]]).T)
    heatmap(c11, lab11, "Acceleration vs dynamic force offset", "fig11_corr_accel_force.png")

    # Figure 12: all kinematic features and wrench components
    lab12 = ["x", "y", "z", "roll", "pitch", "yaw",
             "ax", "ay", "az", "alpha_x", "alpha_y", "alpha_z",
             "Fx_dyn", "Fy_dyn", "Fz_dyn", "Tx_dyn", "Ty_dyn", "Tz_dyn"]
    c12 = np.corrcoef(np.hstack([pos, xdd, y]).T)
    heatmap(c12, lab12, "Kinematic features and dynamic wrench offset", "fig12_corr_full.png")

    save({"fig11": {"labels": lab11, "corr": c11.round(4).tolist()},
          "fig12": {"labels": lab12, "corr": c12.round(4).tolist()}}, RESULTS_DIR / "correlation.json")


if __name__ == "__main__":
    main()
